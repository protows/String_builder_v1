//Обратите внимание, оба метода replace() и replaceFirst() вызываются у объекта
//класса String и одновременно возвращают объект класса String. Это свойство позволяет
//объединить несколько вызовов в цепочку (вызывать подряд можно не только эти, но и
//другие методы String). Например, если в строке вам нужно заменить все буквы «а» на «А», а
//подстроку «зелёный» на «красный», это можно сделать так:
package stringbuilder;
public class String7 {
public static void main(String[] args) {
    String vegetables = "Томат — зелёный, а морковка — оранжевая";
   

System.out.println(vegetables.replace("а", "А").replaceFirst("зелёный", "красный"));
// Выведет: "ТомАт — красный, А морковкА — орАнжевАя"
 }
}
